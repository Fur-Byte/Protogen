"""Check the installed ESP platform and IDF release trees against upstream archives."""

from pathlib import Path

from build_support import file_sha256, source_digest


def package_source_digest(directory, generated):
    if not directory.is_dir() or directory.is_symlink():
        raise RuntimeError(f"Missing or symlinked ESP dependency: {directory}")
    files = {}
    for path in directory.rglob("*"):
        relative = path.relative_to(directory)
        name = relative.as_posix()
        if path.is_symlink():
            raise RuntimeError(f"Unexpected ESP dependency symlink: {path}")
        if path.is_dir():
            continue
        if not path.is_file():
            raise RuntimeError(f"Unexpected ESP dependency entry: {path}")
        if name == ".piopm":
            continue
        # Generated bytecode is not part of the upstream source archive.
        if "__pycache__" in relative.parts and path.suffix == ".pyc":
            continue
        if name in generated:
            if path.read_bytes() != generated[name]:
                raise RuntimeError(f"Unexpected generated ESP dependency content: {path}")
            continue
        files[name] = file_sha256(path)
    return source_digest(files)


def verify_esp_sources(core, lock):
    pins = lock["esp32_source_integrity"]
    generated = {
        "version.txt": lock["esp32"]["esp_idf"].encode(),
        "components/__pio_env/CMakeLists.txt": (
            b"# Warning! Do not delete this auto-generated file.\n"
            b"file(GLOB component_sources *.c* *.S)\n"
            b"idf_component_register(SRCS ${component_sources})\n"
        ),
        **{f"components/__pio_env/__dummy{ext}": b"" for ext in (".c", ".cpp", ".S")},
    }
    verified = {}
    for name, pin in pins.items():
        actual = package_source_digest(
            Path(core) / name, generated if name == "packages/framework-espidf" else {}
        )
        if actual != pin["tree_sha256"]:
            raise RuntimeError(f"Pinned ESP dependency source content mismatch: {name}")
        verified[name] = actual
    return verified
